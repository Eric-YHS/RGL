const TREATMENT_IDS = TREATMENT_MATERIALS.map((m) => m.id);
const TREATMENT_STORAGE_KEY = "honglvdeng_treatment_v1";

export function findTreatment(id: string): TreatmentMaterial | undefined {
  return TREATMENT_MATERIALS.find((m) => m.id === id);
}

export function normalizeTreatmentId(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const normalized = raw.trim().toUpperCase();
  return TREATMENT_IDS.includes(normalized) ? normalized : null;
}

function hashString(text: string): number {
  // djb2：对被试编号做确定性哈希，保证同一 pid 始终进入同一处理组。
  let hash = 5381;
  for (let i = 0; i < text.length; i += 1) {
    hash = ((hash << 5) + hash + text.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function randomTreatmentId(): string {
  if (typeof crypto !== "undefined" && typeof crypto.getRandomValues === "function") {
    const buf = new Uint32Array(1);
    crypto.getRandomValues(buf);
    return TREATMENT_IDS[buf[0] % TREATMENT_IDS.length];
  }
  return TREATMENT_IDS[Date.now() % TREATMENT_IDS.length];
}

export function resolveTreatmentId(search: string, participantId: string): string {
  const params = new URLSearchParams(search);
  const fromParam = normalizeTreatmentId(params.get("treatment"));
  if (fromParam) return fromParam;

  // 同一被试（同一 pid）必须始终进入同一处理组，即使退出再进。
  if (participantId) {
    return TREATMENT_IDS[hashString(participantId) % TREATMENT_IDS.length];
  }

  // 无 pid 时退化为本地持久化随机：刷新/重进保持同一分组。
  try {
    const saved = normalizeTreatmentId(window.localStorage.getItem(TREATMENT_STORAGE_KEY));
    if (saved) return saved;
    const assigned = randomTreatmentId();
    window.localStorage.setItem(TREATMENT_STORAGE_KEY, assigned);
    return assigned;
  } catch {
    return randomTreatmentId();
  }
}
